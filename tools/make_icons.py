#!/usr/bin/env python3
"""Generates icons.r: Diary's icons (ICN#, ICON, icl4, icl8, ics#, ics4, ics8).

The icon is a closed red leather diary with a gold label, a gold clasp
and a blue ribbon bookmark. Run:  python3 tools/make_icons.py > icons.r
"""

# Palette: key -> (icl8 index, icl4 index, 1-bit value or 'dither')
# icl8 indices are from the standard Mac 256-colour CLUT (6x6x6 cube),
# icl4 indices from the standard 16-colour CLUT.
def cube(r, g, b):
    """Index of an RGB colour (components 0..5, 5 = FF) in the 8-bit CLUT."""
    if (r, g, b) == (0, 0, 0):
        return 255
    return (5 - r) * 36 + (5 - g) * 6 + (5 - b)

PALETTE = {
    'K': (255,           15, 1),         # black outline
    'R': (cube(4, 0, 0),  3, 'dither'),  # red leather cover
    'H': (cube(5, 2, 2),  3, 0),         # cover highlight
    'D': (cube(2, 0, 0), 10, 1),         # dark red spine / strap
    'W': (0,              0, 0),         # page white
    'G': (cube(4, 4, 4), 12, 1),         # page edge lines
    'Y': (cube(5, 4, 0),  1, 0),         # gold
    'O': (cube(4, 3, 0), 11, 1),         # dark gold
    'B': (cube(0, 2, 5),  6, 1),         # ribbon
}


def new_grid(n):
    return [['.'] * n for _ in range(n)]


def rect(g, top, left, bottom, right, c):
    for y in range(top, bottom + 1):
        for x in range(left, right + 1):
            g[y][x] = c


def frame(g, top, left, bottom, right, c):
    for x in range(left, right + 1):
        g[top][x] = g[bottom][x] = c
    for y in range(top, bottom + 1):
        g[y][left] = g[y][right] = c


def large():
    g = new_grid(32)
    # Page block peeking out at the right and bottom
    rect(g, 3, 5, 29, 27, 'W')
    frame(g, 3, 5, 29, 27, 'K')
    for y in range(5, 28, 2):
        g[y][26] = 'G'
    for x in range(7, 26, 2):
        g[28][x] = 'G'
    # Cover
    rect(g, 1, 3, 27, 25, 'R')
    frame(g, 1, 3, 27, 25, 'K')
    for x in range(9, 25):
        g[2][x] = 'H'
    for y in range(2, 27):
        g[y][9] = 'H'
    # Spine
    rect(g, 2, 4, 26, 7, 'D')
    for x in range(4, 8):
        g[5][x] = g[23][x] = 'Y'
    for y in range(2, 27):
        g[y][8] = 'K'
    # Gold label with two text lines
    rect(g, 6, 12, 12, 22, 'W')
    frame(g, 6, 12, 12, 22, 'O')
    for x in range(14, 21):
        g[8][x] = 'G'
    for x in range(14, 19):
        g[10][x] = 'G'
    # Strap across the right edge with a gold clasp
    rect(g, 15, 19, 19, 27, 'D')
    frame(g, 15, 19, 19, 27, 'K')
    rect(g, 14, 20, 20, 23, 'Y')
    frame(g, 14, 20, 20, 23, 'K')
    g[17][21] = g[17][22] = 'O'
    # Ribbon bookmark with a notched end
    rect(g, 28, 11, 31, 13, 'B')
    g[31][12] = '.'
    for y in (30, 31):
        g[y][10] = g[y][14] = 'K'
    return g


def small():
    g = new_grid(16)
    rect(g, 2, 3, 15, 14, 'W')
    frame(g, 2, 3, 15, 14, 'K')
    rect(g, 0, 1, 13, 12, 'R')
    frame(g, 0, 1, 13, 12, 'K')
    rect(g, 1, 2, 12, 3, 'D')
    for y in range(1, 13):
        g[y][4] = 'K'
    rect(g, 3, 6, 5, 10, 'W')
    frame(g, 3, 6, 5, 10, 'O')
    rect(g, 7, 10, 9, 14, 'D')
    frame(g, 7, 10, 9, 14, 'K')
    rect(g, 7, 10, 9, 11, 'Y')
    g[14][7] = g[15][7] = 'B'
    return g


def bitmap(g, value_of):
    n = len(g)
    out = bytearray()
    for y in range(n):
        bits = 0
        for x in range(n):
            bits = (bits << 1) | value_of(x, y, g[y][x])
        out += bits.to_bytes(n // 8, 'big')
    return bytes(out)


def one_bit(x, y, c):
    if c == '.':
        return 0
    v = PALETTE[c][2]
    if v == 'dither':
        return (x + y) & 1
    return v


def one_bit_small(x, y, c):
    """At 16x16 a dithered cover is just noise, so leave it white."""
    if c != '.' and PALETTE[c][2] == 'dither':
        return 0
    return one_bit(x, y, c)


def mask(g):
    """Every drawn pixel; the artwork has no transparent holes inside."""
    return bitmap(g, lambda x, y, c: 0 if c == '.' else 1)


def nibbles(g):
    out = bytearray()
    for row in g:
        for x in range(0, len(row), 2):
            a = PALETTE[row[x]][1] if row[x] != '.' else 0
            b = PALETTE[row[x + 1]][1] if row[x + 1] != '.' else 0
            out.append(a << 4 | b)
    return bytes(out)


def bytes8(g):
    return bytes(PALETTE[c][0] if c != '.' else 0 for row in g for c in row)


def rez(kind, rid, data, comment=None):
    lines = []
    if comment:
        lines += ['/*'] + ['    ' + l for l in comment] + ['*/']
    lines.append("data '%s' (%d, purgeable) {" % (kind, rid))
    for i in range(0, len(data), 16):
        lines.append('    $"%s"' % data[i:i + 16].hex(' ', 2).upper())
    lines.append('};')
    return '\n'.join(lines)


def main():
    big, sml = large(), small()
    print('/* Generated by tools/make_icons.py - do not edit by hand. */\n')
    print(rez('ICN#', 128, bitmap(big, one_bit) + mask(big),
              [''.join(r) for r in big]))
    print()
    print(rez('ICON', 128, bitmap(big, one_bit)))   # for the About box
    print()
    print(rez('icl4', 128, nibbles(big)))
    print()
    print(rez('icl8', 128, bytes8(big)))
    print()
    print(rez('ics#', 128, bitmap(sml, one_bit_small) + mask(sml),
              [''.join(r) for r in sml]))
    print()
    print(rez('ics4', 128, nibbles(sml)))
    print()
    print(rez('ics8', 128, bytes8(sml)))


main()
